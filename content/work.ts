const clientTypeFor: Record<ServiceId, ClientType> = {
  vehicles: "vehicle",
  commercial: "commercial",
  residential: "residential",
  engraving: "commercial",
  print: "commercial",
};

// These originals live beside their separately selected hero derivatives.
const heroOriginals = new Set(["airplane", "bedrock", "czvan", "jetski", "signage2", "signage5", "signage7"]);

export const work: Project[] = rows.map(([slug, ext, width, height, service, title]) => ({
  slug,
  title,
  service,
  clientType: clientTypeFor[service],
  item: title,
  materials: [],
  caption: visibleCaptions[slug] ?? title,
  alt: visibleCaptions[slug] ?? title,
  image: { src: `/work/${heroOriginals.has(slug) ? "hero/" : ""}${slug}.${ext}`, width, height },
  featured: featuredOrder.includes(slug),
  verified: false,
}));

const bySlug = new Map(work.map((p) => [p.slug, p]));
export const featuredWork: Project[] = featuredOrder.map((slug) => {
  const p = bySlug.get(slug);
  if (!p) throw new Error(`featuredOrder references unknown slug ${slug}`);
  return p;
});

export function photosFor(service: ServiceId, n = 3): Project[] {
  return featuredWork.filter((p) => p.service === service).slice(0, n);
}

export function publishedPhoto(slug: string): Project {
  const photo = featuredWork.find((project) => project.slug === slug);
  if (!photo) throw new Error(`Photo has not been approved for publication: ${slug}`);
  return photo;
}
